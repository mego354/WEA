NOTIFICATION_EVENTS_BY_CODE: Dict[str, Dict[str, Any]] = {
    ev['code']: ev for ev in NOTIFICATION_EVENTS_CATALOG
}


def get_event_definition(code: str) -> Optional[Dict[str, Any]]:
    return NOTIFICATION_EVENTS_BY_CODE.get(code)


def get_all_notification_events() -> List[Dict[str, Any]]:
    return list(NOTIFICATION_EVENTS_CATALOG)


def get_grouped_notification_events() -> List[Dict[str, Any]]:
    grouped = []
    by_mod: Dict[str, List[Dict[str, Any]]] = {}
    for ev in NOTIFICATION_EVENTS_CATALOG:
        by_mod.setdefault(ev['module'], []).append(ev)
    for mod_key, meta in NOTIFICATION_MODULES_META.items():
        events = by_mod.get(mod_key, [])
        if events:
            grouped.append({
                'code': mod_key,
                'name_ar': meta['name_ar'],
                'icon': meta['icon'],
                'events': events,
            })
    return grouped
